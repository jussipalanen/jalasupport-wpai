<?php

declare(strict_types=1);

namespace JalaSupport\Fields;

use JalaSupport\Models\TicketCategory;
use JalaSupport\Models\TicketMeta;
use JalaSupport\Models\TicketPriority;
use JalaSupport\Models\TicketStatus;
use JalaSupport\PostTypes\TicketPostType;

/**
 * Ticket metadata: post meta registration (sanitization, private) and the
 * ACF field group used in the admin. Field definitions are kept in PHP so
 * they are version-controlled.
 */
final class TicketFields
{
    public const GROUP_KEY = 'group_jalasupport_ticket';

    public static function fieldKey(string $metaKey): string
    {
        return 'field_jalasupport_' . $metaKey;
    }

    public function register(): void
    {
        add_action('init', [$this, 'registerMeta']);
        add_action('acf/include_fields', [$this, 'registerFieldGroup']);
        add_action('admin_notices', [$this, 'missingAcfNotice']);
    }

    public function registerMeta(): void
    {
        foreach ($this->metaSanitizers() as $key => $sanitizer) {
            register_post_meta(TicketPostType::NAME, $key, [
                'type' => 'string',
                'single' => true,
                'default' => '',
                'show_in_rest' => false,
                'sanitize_callback' => $sanitizer,
                'auth_callback' => static fn(bool $allowed, string $metaKey, int $postId): bool => current_user_can('edit_post', $postId),
            ]);
        }
    }

    /**
     * Sanitizer per meta key. Select fields fall back to their default when an
     * unknown value is stored.
     *
     * @return array<string, callable(mixed): string>
     */
    public function metaSanitizers(): array
    {
        return [
            TicketMeta::STATUS => static fn($value): string => (TicketStatus::tryFrom((string) $value) ?? TicketStatus::default())->value,
            TicketMeta::PRIORITY => static fn($value): string => (TicketPriority::tryFrom((string) $value) ?? TicketPriority::default())->value,
            TicketMeta::CATEGORY => static fn($value): string => (TicketCategory::tryFrom((string) $value) ?? TicketCategory::default())->value,
            TicketMeta::CUSTOMER_NAME => static fn($value): string => sanitize_text_field((string) $value),
            TicketMeta::CUSTOMER_EMAIL => static fn($value): string => sanitize_email((string) $value),
            TicketMeta::AI_SUMMARY => static fn($value): string => sanitize_textarea_field((string) $value),
            TicketMeta::AI_SUGGESTED_REPLY => static fn($value): string => sanitize_textarea_field((string) $value),
        ];
    }

    public function registerFieldGroup(): void
    {
        if (! function_exists('acf_add_local_field_group')) {
            return;
        }

        acf_add_local_field_group($this->fieldGroup());
    }

    /**
     * @return array<string, mixed>
     */
    public function fieldGroup(): array
    {
        return [
            'key' => self::GROUP_KEY,
            'title' => __('Ticket details', 'jalasupport'),
            'fields' => [
                $this->select(TicketMeta::STATUS, __('Status', 'jalasupport'), TicketStatus::options(), TicketStatus::default()->value),
                $this->select(TicketMeta::PRIORITY, __('Priority', 'jalasupport'), TicketPriority::options(), TicketPriority::default()->value),
                $this->select(TicketMeta::CATEGORY, __('Category', 'jalasupport'), TicketCategory::options(), TicketCategory::default()->value),
                [
                    'key' => self::fieldKey(TicketMeta::CUSTOMER_NAME),
                    'name' => TicketMeta::CUSTOMER_NAME,
                    'label' => __('Customer name', 'jalasupport'),
                    'type' => 'text',
                    'required' => 1,
                    'maxlength' => 200,
                ],
                [
                    'key' => self::fieldKey(TicketMeta::CUSTOMER_EMAIL),
                    'name' => TicketMeta::CUSTOMER_EMAIL,
                    'label' => __('Customer email', 'jalasupport'),
                    'type' => 'email',
                    'required' => 1,
                ],
                [
                    'key' => self::fieldKey(TicketMeta::AI_SUMMARY),
                    'name' => TicketMeta::AI_SUMMARY,
                    'label' => __('AI summary', 'jalasupport'),
                    'instructions' => __('Generated by AI and saved only after user confirmation.', 'jalasupport'),
                    'type' => 'textarea',
                    'rows' => 3,
                    'new_lines' => '',
                ],
                [
                    'key' => self::fieldKey(TicketMeta::AI_SUGGESTED_REPLY),
                    'name' => TicketMeta::AI_SUGGESTED_REPLY,
                    'label' => __('AI suggested reply', 'jalasupport'),
                    'instructions' => __('Generated by AI and saved only after user confirmation.', 'jalasupport'),
                    'type' => 'textarea',
                    'rows' => 6,
                    'new_lines' => '',
                ],
            ],
            'location' => [
                [
                    [
                        'param' => 'post_type',
                        'operator' => '==',
                        'value' => TicketPostType::NAME,
                    ],
                ],
            ],
            'position' => 'normal',
            'style' => 'default',
            'active' => true,
            'show_in_rest' => 0,
        ];
    }

    public function missingAcfNotice(): void
    {
        if (function_exists('acf_add_local_field_group') || ! current_user_can('activate_plugins')) {
            return;
        }

        printf(
            '<div class="notice notice-warning"><p>%s</p></div>',
            esc_html__('JalaSupport: activate Advanced Custom Fields to edit ticket details in the admin.', 'jalasupport'),
        );
    }

    /**
     * @param  array<string, string>  $choices
     * @return array<string, mixed>
     */
    private function select(string $name, string $label, array $choices, string $default): array
    {
        return [
            'key' => self::fieldKey($name),
            'name' => $name,
            'label' => $label,
            'type' => 'select',
            'required' => 1,
            'choices' => $choices,
            'default_value' => $default,
            'allow_null' => 0,
            'multiple' => 0,
            'ui' => 0,
            'return_format' => 'value',
            'wrapper' => ['width' => '33'],
        ];
    }
}
